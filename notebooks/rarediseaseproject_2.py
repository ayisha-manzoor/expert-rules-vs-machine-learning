# Rule 1
def check_rule_1(person_id, diagnosis_df, labs_df):
# Checking for specific ICD codes in Diagnosis
    organomegaly_conditions = ['R19.0', 'R16.2', 'R16.0', 'R16.1']
    diagnosis_match = diagnosis_df[
        (diagnosis_df['PERSONID'] == person_id) &
        (diagnosis_df['ICDCODE'].isin(organomegaly_conditions))
    ].compute()  # Convert to pandas DataFrame

# Checking CBC parameters in Labs
    labs_match = labs_df[
        (labs_df['PERSONID'] == person_id) &
        (
            (labs_df['RESULTVALUE'] < 4.5) |  # WBC lower limit
            (labs_df['RESULTVALUE'] > 11) |  # WBC upper limit
            (labs_df['RESULTVALUE'] < 132) | # Hb lower limit
            (labs_df['RESULTVALUE'] > 173)   # Hb upper limit
        )
    ].compute()  # Convert to pandas DataFrame

    # Using pandas `.empty` now, as both DataFrames are converted
    return not diagnosis_match.empty and not labs_match.empty

