def check_rule_3(person_id, diagnosis_df, clinical_df, rule1_result, rule2_result):
# Checking for Growth Retardation OR Failure to Thrive OR Low Weight/Height Percentile
    growth_conditions = ['R62.50', 'R62.7']  # Growth retardation and failure to thrive
    diagnosis_match = diagnosis_df[
        (diagnosis_df['PERSONID'] == person_id) &
        (diagnosis_df['ICDCODE'].isin(growth_conditions))
    ]

# Checking for low weight or height percentiles
    clinical_match = clinical_df[
        (clinical_df['PERSONID'] == person_id) &
        (clinical_df['EVENTNAME'].str.contains('WEIGHT|HEIGHT', na=False)) &
        (clinical_df['EVENTRESULT'].astype(float) < 3)  # Below 3rd percentile
    ]

# Rule 3 is triggered if Rule 1 and Rule 2 are YES and conditions are met
    return (
        rule1_result == 'YES' and
        rule2_result == 'YES' and
        (not diagnosis_match.empty or not clinical_match.empty)
    )

